// Generates an exercise library seed SQL file from src/lib/exercises/library.ts.
// Usage: pnpm db:gen-library <output.sql>
// The initial seed migration was generated with this. For later changes, write a
// NEW migration (see 20261029000002_lunge_chain.sql) instead of regenerating it.
import { writeFileSync } from "node:fs";
import { EXERCISES } from "../src/lib/exercises/library";

const OUT = process.argv[2];
if (!OUT) throw new Error("Usage: pnpm db:gen-library <output.sql>");

const str = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (a: string[]) => `array[${a.map(str).join(", ")}]::text[]`;

const rows = EXERCISES.map((e) =>
  `  (${[
    str(e.id), str(e.name), str(e.category), str(e.chain), e.chain_order, e.level,
    arr(e.equipment), str(e.metric), e.unilateral, arr(e.cues), arr(e.contraindications),
    e.media_url ? str(e.media_url) : "null",
  ].join(", ")})`,
);

const sql = `-- Generated by scripts/gen-exercise-seed.ts — do not edit by hand.
-- To change the library, edit src/lib/exercises/library.ts and add a NEW migration.
insert into public.exercises
  (id, name, category, chain, chain_order, level, equipment, metric, unilateral, cues, contraindications, media_url)
values
${rows.join(",\n")}
on conflict (id) do update set
  name = excluded.name, category = excluded.category, chain = excluded.chain,
  chain_order = excluded.chain_order, level = excluded.level, equipment = excluded.equipment,
  metric = excluded.metric, unilateral = excluded.unilateral, cues = excluded.cues,
  contraindications = excluded.contraindications, media_url = excluded.media_url;
`;

writeFileSync(OUT, sql);
console.log(`Wrote ${EXERCISES.length} exercises to ${OUT}`);
